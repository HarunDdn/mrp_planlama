-- CANIAS stok dokumu -> MRP_Girdi.xlsm > STOK sekmesi
-- Sekmedeki "CANIAS'tan Guncelle" butonu bu sorguyu calistirir. Kolon adlari (AS [..])
-- dogrudan sekme basliklari olur; veri_aktar.py "Malzeme", "Depo", "Kullanılabilir Stok"
-- basliklarini okur, bunlari degistirmeyin.
-- Degistirdikten sonra:  python excel_kurulum.py   (sorguyu calisma kitabina yukler)
--
-- Kaynak: CANIAS stok raporu. Duzeltmeler: tarihler GETDATE(), depo filtresi WAREHOUSE
-- (sekmedeki "Depo" = WAREHOUSE, "St.Yeri" = STOCKPLACE), ORDER BY yazimi.
WITH S AS (
SELECT IASINVSTOCK.MATERIAL, IASINVSTOCK.VARIANTKEY, IASINVSTOCK.VOPTIONS,
       IASINVSTOCK.COMPANY, IASINVSTOCK.PLANT, IASINVSTOCK.WAREHOUSE, IASINVSTOCK.STOCKPLACE,
       IASINVSTOCK.BASESTOCKPLACE, IASINVSTOCK.QUNIT, IASINVSTOCK.QUNITX, IASMATX.STEXT,
       MAX(IASINVSTOCK.EXPIRYDATE) AS EXPIRYDATE, IASINVSTOCK.SPECIALSTOCK AS SPECIAL, IASINVSTOCK.BATCHNUM AS BATCH,
       SUM(IASINVSTOCK.TOTALSTOCK) AS TOTALSTOCK, SUM(IASINVSTOCK.AVAILSTOCK) AS AVAILSTOCK,
       SUM(IASINVSTOCK.TRANSTOCK) AS TRANSTOCK, SUM(IASINVSTOCK.BLOCKSTOCK) AS BLOCKSTOCK,
       SUM(IASINVSTOCK.QUALITYSTOCK) AS QUALITYSTOCK, SUM(IASINVSTOCK.RESERVESTOCK) AS RESERVESTOCK,
       SUM(IASINVSTOCK.REVISESTOCK) AS REVISESTOCK,
       SUM(IASINVSTOCK.TOTALSTOCK2) AS TOTALSTOCK2, SUM(IASINVSTOCK.AVAILSTOCK2) AS AVAILSTOCK2,
       SUM(IASINVSTOCK.TRANSTOCK2) AS TRANSTOCK2, SUM(IASINVSTOCK.BLOCKSTOCK2) AS BLOCKSTOCK2,
       SUM(IASINVSTOCK.QUALITYSTOCK2) AS QUALITYSTOCK2, SUM(IASINVSTOCK.RESERVESTOCK2) AS RESERVESTOCK2,
       SUM(IASINVSTOCK.REVISESTOCK2) AS REVISESTOCK2,
       IASINVSTOCK.AVAILVOLUMECAP, MAX(IASMATBASIC.BWUNIT) AS WEIGHTUNIT,
       IASINVSTOCK.AVAILWEIGHTCAP, MAX(IASMATBASIC.VUNIT) AS VOLUMEUNIT,
       MAX(CASE WHEN MV.CLIENT IS NOT NULL THEN MV.FLXPRICE ELSE FM.FLXPRICE END) AS REPORTPRICE,
       FM.FINPUNIT AS FINPUNIT, FM.FINCURRENCY,
       (SELECT SUM(QUANTITY)
          FROM IASRESERVATION R
         WHERE R.CLIENT = '00'
           AND R.COMPANY = IASINVSTOCK.COMPANY
           AND R.PLANT = IASINVSTOCK.PLANT
           AND R.MATERIAL = IASINVSTOCK.MATERIAL
           AND R.VOPTIONS = IASINVSTOCK.VOPTIONS
           AND R.WAREHOUSE = IASINVSTOCK.WAREHOUSE
           AND R.STOCKPLACE = IASINVSTOCK.STOCKPLACE
           AND R.SPECIALSTOCK = IASINVSTOCK.SPECIALSTOCK
           AND R.BATCHNUM = IASINVSTOCK.BATCHNUM
           AND R.EXPIRYDATE >= GETDATE()
           AND R.ISCANCELED = 0) AS SOFTRESSTOCK
  FROM IASINVSTOCK
  LEFT OUTER JOIN IASMATX ON (IASMATX.CLIENT = '00'
           AND IASMATX.LANGU = 'T'
           AND IASMATX.PLANT = '*'
           AND IASMATX.TEXTTYPE = 'B'
           AND IASMATX.VALIDFROM <= CAST(GETDATE() AS date)
           AND IASMATX.VALIDUNTIL >= CAST(GETDATE() AS date)
           AND IASMATX.MATERIAL = IASINVSTOCK.MATERIAL
           AND IASMATX.COMPANY = IASINVSTOCK.COMPANY)
  LEFT OUTER JOIN IASMATFMS FM ON (FM.CLIENT = IASINVSTOCK.CLIENT
           AND FM.COMPANY = IASINVSTOCK.COMPANY
           AND FM.PLANT = IASINVSTOCK.PLANT
           AND FM.MATERIAL = IASINVSTOCK.MATERIAL
           AND FM.VALIDFROM <= CAST(GETDATE() AS date)
           AND FM.VALIDUNTIL >= CAST(GETDATE() AS date))
  LEFT OUTER JOIN IASMATVARPRICE MV ON (MV.CLIENT = IASINVSTOCK.CLIENT
           AND MV.COMPANY = IASINVSTOCK.COMPANY
           AND MV.PLANT = IASINVSTOCK.PLANT
           AND MV.MATERIAL = IASINVSTOCK.MATERIAL
           AND MV.VOPTIONSPRICE = IASINVSTOCK.VOPTIONS
           AND MV.VALIDFROM <= CAST(GETDATE() AS date)
           AND MV.VALIDUNTIL >= CAST(GETDATE() AS date)),
       IASMATBASIC
 WHERE IASINVSTOCK.CLIENT = '00'
   AND IASINVSTOCK.COMPANY = '01'
   AND IASINVSTOCK.WAREHOUSE IN ('100', '200', '300')
   AND IASINVSTOCK.ENTRYDATE >= '1975-01-01'
   AND IASINVSTOCK.EXPIRYDATE <= '2100-01-01'
   AND IASMATBASIC.CLIENT = '00'
   AND IASMATBASIC.COMPANY = IASINVSTOCK.COMPANY
   AND IASMATBASIC.MATERIAL = IASINVSTOCK.MATERIAL
   AND IASMATBASIC.VALIDFROM <= CAST(GETDATE() AS date)
   AND IASMATBASIC.VALIDUNTIL >= CAST(GETDATE() AS date)
 GROUP BY IASINVSTOCK.MATERIAL, IASINVSTOCK.VARIANTKEY, IASINVSTOCK.VOPTIONS, FM.FINCURRENCY,
          IASINVSTOCK.COMPANY, IASINVSTOCK.PLANT, IASINVSTOCK.WAREHOUSE, IASINVSTOCK.STOCKPLACE,
          IASINVSTOCK.BASESTOCKPLACE, IASINVSTOCK.SPECIALSTOCK, IASINVSTOCK.BATCHNUM,
          IASINVSTOCK.QUNIT, IASINVSTOCK.QUNITX, IASMATX.STEXT,
          IASINVSTOCK.AVAILWEIGHTCAP, IASINVSTOCK.AVAILVOLUMECAP, FM.FINPUNIT
)
SELECT PLANT                      AS [Tesis],
       WAREHOUSE                  AS [Depo],
       STOCKPLACE                 AS [St.Yeri],
       SPECIAL                    AS [Ö.St.Tipi],
       BATCH                      AS [Parti],
       MATERIAL                   AS [Malzeme],
       STEXT                      AS [Açıklama],
       TOTALSTOCK                 AS [Toplam Stok],
       AVAILSTOCK                 AS [Kullanılabilir Stok],
       QUNIT                      AS [Miktar Br.],
       EXPIRYDATE                 AS [SKT],
       REPORTPRICE                AS [Fiyat],
       ROUND(TOTALSTOCK * REPORTPRICE / COALESCE(NULLIF(FINPUNIT, 0), 1), 2) AS [Tutar],
       QUALITYSTOCK               AS [Kalite Stoğu],
       BLOCKSTOCK                 AS [Bloke Stoğu],
       TRANSTOCK                  AS [Transfer Stok],
       RESERVESTOCK               AS [Rezerve Stok],
       REVISESTOCK                AS [Revize Stok],
       SOFTRESSTOCK               AS [Sanal Rezervasyon],
       QUNITX                     AS [2.Miktar Br.],
       TOTALSTOCK2                AS [2.Toplam Stok],
       AVAILSTOCK2                AS [2.Kullanılabilir Stok],
       QUALITYSTOCK2              AS [2.Kalite Stoğu],
       BLOCKSTOCK2                AS [2.Bloke Stoğu],
       TRANSTOCK2                 AS [2.Transfer Stok],
       RESERVESTOCK2              AS [2.Rezerve Stok],
       REVISESTOCK2               AS [2.Revize Stok],
       AVAILVOLUMECAP             AS [Hacim],
       VOLUMEUNIT                 AS [Hacim Br.],
       AVAILWEIGHTCAP             AS [Ağırlık],
       WEIGHTUNIT                 AS [Ağırlık Br.],
       FINCURRENCY                AS [Pr. Br.],
       VOPTIONS                   AS [Seçenekler],
       BASESTOCKPLACE             AS [Gerçek Stokyeri]
  FROM S
 ORDER BY MATERIAL, WAREHOUSE, STOCKPLACE, BATCH;
